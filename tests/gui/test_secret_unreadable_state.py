"""A stored-but-unreachable secret must not look unset (#192).

A build whose keychain is out of reach (no keyring module, denied access)
reads every secret as empty. The ledger still knows a value was saved, and
the settings form must say so: a field that merely looks blank is how a
user concludes that updates eat his API key — and retypes it into a
different store.
"""
import os

import pytest

pytest.importorskip("PySide6")
os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")

from PySide6.QtWidgets import QApplication                      # noqa: E402

from aglaia.gui.PluginsTab import PluginSettingsDialog          # noqa: E402
from aglaia.plugin_api import Destination, Field                # noqa: E402


class _Store(dict):
    available = True

    def get(self, key, default=None):
        return dict.get(self, key, default)

    def set(self, key, value):
        self[key] = value

    def delete(self, key):
        self.pop(key, None)


class _UnreadableSecrets(_Store):
    """The ledger lists names, every read comes back empty — exactly what a
    keychain the build cannot open looks like through `PluginSecrets`."""

    def __init__(self, names):
        super().__init__()
        self._names = list(names)

    def keys(self):  # type: ignore[override]
        return list(self._names)

    def get(self, key, default=None):
        return None


class _Ctx:
    def __init__(self, secrets):
        self.config = _Store()
        self.secrets = secrets


class _Dest(Destination):
    name = "probe"
    display = "Probe"
    CONFIG_FIELDS = (Field("base_url", "URL", "str", ""),)
    SECRET_FIELDS = (Field("api_key", "API key", "secret",
                           placeholder="Generated by your Corpus instance."),)


@pytest.fixture(scope="module")
def app():
    return QApplication.instance() or QApplication([])


def _field(dlg):
    return dlg._widgets["api_key"][1]


def test_an_unreadable_secret_says_so(app):
    d = _Dest()
    d.ctx = _Ctx(_UnreadableSecrets(["api_key"]))
    dlg = PluginSettingsDialog(d)
    assert "unreadable" in _field(dlg).placeholderText()


def test_an_unset_secret_keeps_the_plugin_placeholder(app):
    d = _Dest()
    d.ctx = _Ctx(_Store())
    dlg = PluginSettingsDialog(d)
    assert _field(dlg).placeholderText() == "Generated by your Corpus instance."


def test_a_readable_secret_still_reads_as_stored(app):
    d = _Dest()
    d.ctx = _Ctx(_Store())
    d.ctx.secrets.set("api_key", "k-123")
    dlg = PluginSettingsDialog(d)
    assert "stored" in _field(dlg).placeholderText()
